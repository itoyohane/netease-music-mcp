import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { randomUUID, createHash } from 'node:crypto';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';

const exec = promisify(execFile);
export const stateDir = process.env.NETEASE_STATE_DIR || path.join(os.homedir(), '.netease-music-plugin');
const sessionFile = path.join(stateDir, 'session.json');
export function safeName(value) {
  const name = String(value).replace(/[<>:"/\\|?*\x00-\x1f]/g, '_').replace(/[. ]+$/g, '').slice(0, 120);
  return /^(con|prn|aux|nul|com[1-9]|lpt[1-9])(?:\.|$)/i.test(name) ? `_${name}` : name || 'track';
}
export function audioType(bytes) {
  if (bytes.subarray(0, 4).toString() === 'fLaC') return 'flac';
  if (bytes.subarray(0, 3).toString() === 'ID3' || (bytes[0] === 255 && (bytes[1] & 224) === 224)) return 'mp3';
  if (bytes.subarray(0, 8).toString() === 'CTENFDAM') return 'ncm';
  throw new Error('文件头不是支持的 FLAC、MP3 或 NCM；未保存为音乐。');
}
export function songView(s) {
  return {id: s.id, name: s.name, artists: (s.ar || s.artists || []).map(a => a.name),
    album: (s.al || s.album)?.name, duration_ms: s.dt || s.duration,
    url: `https://music.163.com/#/song?id=${s.id}`};
}
export function summarize(songs, total) {
  const artists = new Map();
  for (const s of songs) for (const a of s.artists) artists.set(a, (artists.get(a) || 0) + 1);
  return {analyzed: songs.length, total, complete: songs.length === total,
    duration_minutes: Math.round(songs.reduce((n, s) => n + (s.duration_ms || 0), 0) / 60000),
    top_artists: [...artists].sort((a, b) => b[1] - a[1]).slice(0, 20).map(([name, tracks]) => ({name, tracks}))};
}
async function absoluteDir(value) {
  if (!path.isAbsolute(value)) throw new Error('输出目录必须是绝对路径。');
  await fs.mkdir(value, {recursive: true});
  return fs.realpath(value);
}
async function saveCookie(cookie) {
  await fs.mkdir(stateDir, {recursive: true, mode: 0o700});
  let session = {cookie};
  if (process.platform === 'win32') {
    // DPAPI protects the cookie for this Windows user. Secret travels through stdin, not argv.
    session = {dpapi: await dpapi(cookie, false)};
  }
  const temp = `${sessionFile}.${randomUUID()}.tmp`;
  await fs.writeFile(temp, JSON.stringify(session), {mode: 0o600, flag: 'wx'});
  await fs.rename(temp, sessionFile);
}
async function dpapi(value, decrypt) {
  const script = decrypt
    ? '$s=[Console]::In.ReadToEnd(); $b=[Convert]::FromBase64String($s); [Console]::Write([Text.Encoding]::UTF8.GetString([Security.Cryptography.ProtectedData]::Unprotect($b,$null,[Security.Cryptography.DataProtectionScope]::CurrentUser)))'
    : '$s=[Console]::In.ReadToEnd(); $b=[Text.Encoding]::UTF8.GetBytes($s); [Console]::Write([Convert]::ToBase64String([Security.Cryptography.ProtectedData]::Protect($b,$null,[Security.Cryptography.DataProtectionScope]::CurrentUser)))';
  return new Promise((resolve, reject) => {
    const child = execFile('powershell.exe', ['-NoProfile', '-NonInteractive', '-Command', `Add-Type -AssemblyName System.Security; ${script}`], {windowsHide: true, timeout: 15000}, (err, stdout) => err ? reject(new Error('Windows 本机登录信息加解密失败。')) : resolve(stdout));
    child.stdin.end(value);
  });
}
async function loadCookie() {
  try {
    const s = JSON.parse(await fs.readFile(sessionFile, 'utf8'));
    return s.dpapi ? await dpapi(s.dpapi, true) : s.cookie || '';
  } catch (e) { if (e.code === 'ENOENT') return ''; throw e; }
}

export class Music {
  constructor(api, options = {}) { this.api = api; this.cookie = options.cookie; }
  async call(name, args = {}, auth = true) {
    const cookie = this.cookie ?? await loadCookie();
    if (auth && !cookie) throw new Error('请先扫码登录：login_qr，然后 login_check。客户端登录态不会自动导入。');
    let response;
    try { response = await this.api[name]({...args, cookie, timestamp: Date.now()}); }
    catch { throw new Error(`网易云接口 ${name} 请求失败，请检查网络或重新登录。`); }
    const b = response.body;
    if (!b || (b.code && b.code !== 200 && ![800, 801, 802, 803].includes(b.code))) {
      throw new Error(`网易云接口 ${name} 返回 ${b?.code || response.status}，可能登录过期或无权限。`);
    }
    return b;
  }
  async status() {
    const cookie = this.cookie ?? await loadCookie();
    let profile = null;
    if (cookie) profile = (await this.call('login_status')).data?.profile;
    let converter = false;
    try { await exec(process.env.NCMDUMP_PATH || 'ncmdump', ['--version'], {windowsHide: true, timeout: 5000}); converter = true; } catch {}
    return {logged_in: !!profile, user: profile ? {id: profile.userId, nickname: profile.nickname} : null,
      ncmdump_available: converter, state_directory: stateDir};
  }
  async login_qr() {
    const key = (await this.call('login_qr_key', {}, false)).data.unikey;
    // Upstream issue #1: web QR login requires the chainId generated by web mode.
    const data = (await this.call('login_qr_create', {key, qrimg: true, platform: 'web'}, false)).data;
    await fs.mkdir(stateDir, {recursive: true, mode: 0o700});
    const file = path.join(stateDir, `login-${randomUUID()}.png`);
    const match = /^data:image\/png;base64,(.+)$/.exec(data.qrimg);
    if (!match) throw new Error('二维码响应格式异常。');
    await fs.writeFile(file, Buffer.from(match[1], 'base64'), {mode: 0o600});
    return {key, qr_image_path: file, url: data.qrurl, instruction: '使用网易云音乐手机 App 扫码并确认，然后调用 login_check。'};
  }
  async login_check({key}) {
    const b = await this.call('login_qr_check', {key}, false);
    if (b.code === 803) {
      if (!b.cookie) throw new Error('扫码成功但未收到登录信息，请重新扫码。');
      await saveCookie(b.cookie);
      this.cookie = undefined;
    }
    return {code: b.code, logged_in: b.code === 803,
      message: ({800: '二维码已过期', 801: '等待扫码', 802: '等待手机确认', 803: '登录成功'})[b.code] || '未知登录状态'};
  }
  async login_browser() {
    const {browserLogin} = await import('./browser-login.mjs');
    const cookie = await browserLogin({stateDir});
    const response = await this.api.login_status({cookie, timestamp: Date.now()});
    const profile = response.body?.data?.profile;
    if (!profile) throw new Error('官方网页登录完成，但接口未确认账号，请重试。');
    await saveCookie(cookie);
    this.cookie = undefined;
    return {logged_in: true, user: {id: profile.userId, nickname: profile.nickname}};
  }
  async logout() { await fs.rm(sessionFile, {force: true}); this.cookie = ''; return {local_session_removed: true}; }
  async daily() {
    const b = await this.call('recommend_songs');
    return {fetched_at: new Date().toISOString(), service_date: new Intl.DateTimeFormat('sv-SE', {timeZone: 'Asia/Shanghai'}).format(new Date()),
      songs: (b.data?.dailySongs || b.recommend || []).map(songView)};
  }
  async search({keywords, limit = 20}) {
    const b = await this.call('cloudsearch', {keywords, type: 1, limit}, false);
    return {total: b.result?.songCount || 0, songs: (b.result?.songs || []).map(songView)};
  }
  async playlists({offset = 0, limit = 50} = {}) {
    const profile = (await this.call('login_status')).data?.profile;
    if (!profile) throw new Error('登录已失效，请重新扫码。');
    const b = await this.call('user_playlist', {uid: profile.userId, offset, limit});
    return {more: !!b.more, next_offset: offset + (b.playlist || []).length,
      playlists: (b.playlist || []).map(p => ({id: p.id, name: p.name, track_count: p.trackCount,
        description: p.description, tags: p.tags, owned: p.creator?.userId === profile.userId}))};
  }
  async playlist({id, offset = 0, limit = 200}) {
    const p = (await this.call('playlist_detail', {id})).playlist;
    if (!p) throw new Error('歌单不存在或不可访问。');
    const ids = (p.trackIds || []).slice(offset, offset + limit).map(s => s.id);
    const songs = [];
    for (let i = 0; i < ids.length; i += 100) {
      const b = await this.call('song_detail', {ids: ids.slice(i, i + 100).join(',')});
      songs.push(...(b.songs || []).map(songView));
    }
    const next = offset + ids.length;
    return {id, name: p.name, description: p.description, tags: p.tags, songs,
      statistics: summarize(songs, p.trackCount), more: next < (p.trackIds || []).length,
      next_offset: next, inaccessible_count: Math.max(0, p.trackCount - (p.trackIds || []).length)};
  }
  async download({id, output_dir, quality = 'exhigh', playback_fallback = true}) {
    const usable = data => data?.url && (!data.code || data.code === 200) &&
      !data.freeTrialInfo && !data.freeTrialPrivilege?.resConsumable;
    let data, primaryFailure, source = 'download';
    try {
      const b = await this.call('song_download_url_v1', {id, level: quality});
      data = Array.isArray(b.data) ? b.data[0] : b.data;
      if (!usable(data)) primaryFailure = `下载接口未提供完整曲目（code=${data?.code ?? b.code ?? 'unknown'}）`;
    } catch (e) { primaryFailure = e.message; }
    if (primaryFailure) {
      if (!playback_fallback) throw new Error(`${primaryFailure}；未启用播放接口回退，请检查额度、权限或接口状态。`);
      try {
        const b = await this.call('downlist_player_url', {id, level: quality});
        data = Array.isArray(b.data) ? b.data[0] : b.data;
        if (!usable(data)) throw new Error('播放接口没有返回完整曲目，可能无权限或仅有试听。');
        if (Number(data.id) !== id) throw new Error('播放接口返回的曲目 ID 不匹配。');
        source = 'downlist_player';
      } catch (e) { throw new Error(`${primaryFailure}；回退失败：${e.message}`); }
    }
    const details = (await this.call('song_detail', {ids: String(id)})).songs?.[0];
    if (source === 'downlist_player' && (!details?.dt || !Number.isFinite(data.time) ||
      Math.abs(data.time - details.dt) > 2000)) {
      throw new Error('播放接口返回的时长与原曲不符或缺失，未保存可能的试听片段。');
    }
    const dir = await absoluteDir(output_dir);
    const temp = path.join(dir, `.download-${randomUUID()}.part`);
    try {
      let url = new URL(data.url);
      let response;
      for (let i = 0; i < 6; i++) {
        if (!['http:', 'https:'].includes(url.protocol) || !/(^|\.)(music\.126\.net|music\.163\.com|music\.127\.net)$/.test(url.hostname) || url.username || url.password) throw new Error('下载地址不是网易云音乐 CDN。');
        url.protocol = 'https:';
        response = await fetch(url, {redirect: 'manual', signal: AbortSignal.timeout(120000)});
        if (![301, 302, 303, 307, 308].includes(response.status)) break;
        const next = response.headers.get('location');
        await response.body?.cancel();
        if (!next) throw new Error('下载重定向缺少地址。');
        url = new URL(next, url);
      }
      if (!response?.ok || !response.body) throw new Error('下载服务器响应失败。');
      const hash = createHash('md5');
      let size = 0;
      const file = await fs.open(temp, 'wx');
      try {
        for await (const chunk of response.body) {
          size += chunk.length;
          if (size > 512 * 1024 * 1024) throw new Error('单曲超过 512 MiB 上限。');
          hash.update(chunk);
          await file.writeFile(chunk);
        }
      } finally { await file.close(); }
      if (data.size && size !== Number(data.size)) throw new Error('下载长度不匹配，文件不完整。');
      if (data.md5 && hash.digest('hex') !== data.md5.toLowerCase()) throw new Error('下载校验失败。');
      const handle = await fs.open(temp, 'r');
      const header = Buffer.alloc(16);
      try { await handle.read(header, 0, 16, 0); } finally { await handle.close(); }
      const type = audioType(header);
      const name = safeName(`${details?.name || id} - ${(details?.ar || []).map(a => a.name).join(', ')} [${id}]`);
      const target = path.join(dir, `${name}.${type}`);
      await fs.copyFile(temp, target, 1); // COPYFILE_EXCL: preserve existing files.
      return {path: target, bytes: size, format: type, requested_quality: quality,
        actual_bitrate: data.br, needs_ncm_conversion: type === 'ncm',
        source, ...(primaryFailure ? {primary_failure: primaryFailure} : {})};
    } finally { await fs.rm(temp, {force: true}); }
  }
  async convert_ncm({input_file, output_dir}) {
    if (!path.isAbsolute(input_file) || path.extname(input_file).toLowerCase() !== '.ncm') throw new Error('请指定 .ncm 文件的绝对路径。');
    const input = await fs.realpath(input_file);
    if (!(await fs.stat(input)).isFile()) throw new Error('输入必须是文件。');
    const dir = await absoluteDir(output_dir);
    const staging = await fs.mkdtemp(path.join(dir, '.ncmdump-'));
    try {
      try { await exec(process.env.NCMDUMP_PATH || 'ncmdump', [input, '-o', staging], {windowsHide: true, timeout: 180000, maxBuffer: 1024 * 1024}); }
      catch (e) { throw new Error(e.code === 'ENOENT' ? '未找到 ncmdump，请安装或设置 NCMDUMP_PATH。' : 'ncmdump 转换失败，原始文件已保留。'); }
      const entries = await fs.readdir(staging, {withFileTypes: true});
      const outputs = entries.filter(e => e.isFile() && /\.(flac|mp3)$/i.test(e.name));
      if (outputs.length !== 1) throw new Error('ncmdump 未生成唯一的 MP3/FLAC 文件。');
      const source = path.join(staging, outputs[0].name);
      const file = await fs.open(source, 'r');
      const header = Buffer.alloc(16);
      try { await file.read(header, 0, 16, 0); } finally { await file.close(); }
      const format = audioType(header);
      if (!['flac', 'mp3'].includes(format)) throw new Error('转换输出格式异常。');
      const target = path.join(dir, `${safeName(path.parse(input).name)}.${format}`);
      await fs.copyFile(source, target, 1);
      return {path: target, format, source_preserved: true};
    } finally { await fs.rm(staging, {recursive: true, force: true}); }
  }
}
